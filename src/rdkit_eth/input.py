"""Input validation and provenance in RDKit atom-index order."""

from __future__ import annotations

import hashlib
import json
import math
from numbers import Integral
from typing import Any


def _method_flag(method: str) -> tuple[str, str]:
    key = method.strip().lower().replace('_', '-').replace('-xtb', '')
    methods = {
        'gfn0': ('GFN0-xTB', '--gfn0'),
        'gfn1': ('GFN1-xTB', '--gfn1'),
        'gfn2': ('GFN2-xTB', '--gfn2'),
        'gfnff': ('GFN-FF', '--gfnff'),
        'gfn-ff': ('GFN-FF', '--gfnff'),
    }
    if key not in methods:
        raise ValueError(f'unsupported xTB method {method!r}')
    return methods[key]


def _geometry_hash(xyz: str) -> str:
    return hashlib.sha256(xyz.encode()).hexdigest()


def _ordered_structure_hash(mol: Any) -> str:
    """Fingerprint indexed topology, including isotopes, maps and stereochemistry."""
    atoms = [
        (a.GetAtomicNum(), a.GetIsotope(), a.GetFormalCharge(),
         a.GetNumRadicalElectrons(), str(a.GetChiralTag()), a.GetAtomMapNum(),
         a.GetNumImplicitHs(), a.GetNumExplicitHs())
        for a in mol.GetAtoms()
    ]
    bonds = sorted(
        (b.GetBeginAtomIdx(), b.GetEndAtomIdx(), str(b.GetBondType()),
         str(b.GetStereo()), list(b.GetStereoAtoms()))
        for b in mol.GetBonds()
    )
    return _geometry_hash(json.dumps([atoms, bonds], separators=(',', ':')))


def _xyz_from_mol(mol: Any, conf_id: int) -> str:
    if not mol.GetNumAtoms():
        raise ValueError('the molecule must contain atoms')
    if not mol.GetNumConformers():
        raise ValueError('the molecule must have a 3D conformer')
    # [NH4+] and [nH] have explicit H *counts*, but no hydrogen vertices.
    if any(a.GetNumImplicitHs() or a.GetNumExplicitHs() for a in mol.GetAtoms()):
        raise ValueError(
            'the molecule contains implicit hydrogens or hydrogen counts without atoms; '
            'call Chem.AddHs(mol) before run_xtb'
        )
    conf = mol.GetConformer(conf_id)
    if not conf.Is3D():
        raise ValueError('the selected conformer must be marked as 3D')
    lines = [str(mol.GetNumAtoms()), 'generated by rdkit_eth']
    for atom in mol.GetAtoms():
        if atom.GetAtomicNum() <= 0:
            raise ValueError('dummy atoms are not supported by xTB')
        p = conf.GetAtomPosition(atom.GetIdx())
        if not all(math.isfinite(v) for v in (p.x, p.y, p.z)):
            raise ValueError('conformer coordinates must be finite')
        lines.append(f'{atom.GetSymbol()} {p.x:.17g} {p.y:.17g} {p.z:.17g}')
    return '\n'.join(lines) + '\n'


def _effective_charge_uhf(mol: Any, charge: int | None, uhf: int | None) -> tuple[int, int]:
    if charge is None:
        charge = sum(a.GetFormalCharge() for a in mol.GetAtoms())
    if uhf is None:
        uhf = sum(a.GetNumRadicalElectrons() for a in mol.GetAtoms())
    if any(isinstance(v, bool) or not isinstance(v, Integral) for v in (charge, uhf)):
        raise ValueError('charge and uhf must be integers')
    ne = sum(a.GetAtomicNum() for a in mol.GetAtoms()) - charge
    if ne < 1 or uhf < 0 or uhf > ne or (ne - uhf) % 2:
        raise ValueError('charge and uhf are inconsistent with the electron count')
    return int(charge), int(uhf)


def _input_metadata(mol: Any, conf_id: int, charge: int, uhf: int, xyz: str) -> dict:
    return {
        'atom_count': mol.GetNumAtoms(),
        'atomic_numbers': [a.GetAtomicNum() for a in mol.GetAtoms()],
        'ordered_structure_sha256': _ordered_structure_hash(mol),
        'geometry_sha256': _geometry_hash(xyz),
        'charge': charge,
        'uhf': uhf,
        'conformer_id': mol.GetConformer(conf_id).GetId(),
    }
